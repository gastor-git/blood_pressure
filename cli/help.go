package cli

import "fmt"

// helpText — справка CLI: команды, общие опции фильтрации, формат CSV и примеры.
const helpText = `CLI для управления базой данных показаний давления.

Команды:
  export  выгрузить показания в CSV-файл
  delete  удалить показания (требует --yes)
  help    показать эту справку

Общие опции фильтрации (для export и delete):
  -user-id N         только записи пользователя с идентификатором N
  -user-name NAME    только записи с точным совпадением user_name
  -from ДД.ММ.ГГГГ   записи с датой не раньше указанной (включительно)
  -to ДД.ММ.ГГГГ     записи с датой не позже указанной (включительно)

export:
  -out PATH          путь к файлу выгрузки (по умолчанию export_<сегодня>.csv)
  Без фильтров выгружаются все записи. Формат CSV: UTF-8 с BOM, разделитель ";",
  одна строка на (пользователь, дата), отсутствующие части суток — пустые
  ячейки. Шапка: User_ID;User_name;Дата;Утро;День;Вечер.

delete:
  -yes               обязательное подтверждение удаления. Без него команда
                     отказывает. Без фильтров удаляет ВСЕ записи.

Примеры:
  go run . export -user-name alice -from 01.01.2026
  go run . export -user-id 7 -out /tmp/export.csv
  go run . delete -yes
  go run . delete -user-name bob -from 01.01.2026 -to 31.01.2026 -yes
`

func runHelp() {
	fmt.Print(helpText)
}
